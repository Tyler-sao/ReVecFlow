def compare(out, ref):
    err = np.abs(out - ref)
    bad = err > 1e-4 + 1e-4 * np.abs(ref)
    return {"elements": int(ref.size), "failing": int(bad.sum()), "max_abs_err": float(err.max()) if err.size else 0.0,
            "ref_max_abs": float(np.abs(ref).max()) if ref.size else 0.0}


def baseline_accept(got, ref, scalar):
    """Decision 2026-10-17: a blocked output checked against float64 that has elements beyond tolerance
    (atol = rtol = 1e-4, unchanged) is accepted only if every one of them is also beyond tolerance for FuseFlow's own
    scalar output of the same kernel on the same inputs, with the blocked error there no larger than the scalar error
    (ill-conditioned elements that float32 FuseFlow itself cannot meet). Every such element is recorded."""
    tol = 1e-4 + 1e-4 * np.abs(ref)
    eb, es = np.abs(got - ref), np.abs(scalar - ref)
    bb, bs = eb > tol, es > tol
    ok = bool(bb.any() and np.all(bs[bb]) and np.all(eb[bb] <= es[bb]))
    return {"accepted": ok, "rule": "blocked failing elements all fail for FuseFlow's scalar output too, with no larger error",
            "blocked_failing": int(bb.sum()), "scalar_failing": int(bs.sum()), "both_failing": int((bb & bs).sum()),
            "max_err_blocked_there": float(eb[bb].max()) if bb.any() else 0.0,
            "max_err_scalar_there": float(es[bb].max()) if bb.any() else 0.0,
            "elements": [[int(i) for i in w] for w in np.argwhere(bb)[:20]]}


# ---------------------------------------------------------------- blocked layouts
MASK = -1e30   # padding value on the reduced (column) axis of a kernel with a row max reduction (masked softmax)


def has_row_max(mlir_text):
    """True if a (non-commented) linalg.generic reduces with arith.maximumf over a reduction iterator (a row max)."""
    code = "\n".join(l for l in mlir_text.splitlines() if not l.lstrip().startswith("//"))
    return any('"reduction"' in g and "arith.maximumf" in g for g in code.split("linalg.generic")[1:])


def write_blocked_dense(a, formats, prefix, n, mask_cols=False):
    """2-D dense array, padded (with MASK in the padded columns if mask_cols, else 0); reuses the B2/C writer."""
    import b2_block_timing as b2
    r, c = a.shape
    p = np.zeros((-(-r // n) * n, -(-c // n) * n), dtype=np.float32)
    p[:r, :c] = a
    if mask_cols:
        p[:r, c:] = MASK
    cshape, stored = b2.write_blocked(p, formats, prefix, n)
    return {"padded": list(p.shape), "stored_tiles": stored}


def write_blocked_sparse(m, formats, prefix, n):
    """2-D CSR matrix with both levels compressed, in n x n tiles without densifying: level 0 = tile rows holding a
    nonzero, level 1 = their tile columns, values = each stored tile's n*n values row-major."""
    if formats != ["compressed", "compressed"]:
        # e.g. CSR (dense rows, compressed columns) node features X: written through the dense writer, which keeps
        # every tile row (dense level) and stores only the tiles holding a nonzero (compressed level)
        if m.shape[0] * m.shape[1] > 2_000_000_000:
            raise ValueError(f"{formats} tensor of shape {m.shape} too large to write through the dense writer")
        return write_blocked_dense(np.asarray(m.toarray(), dtype=np.float32), formats, prefix, n)
    coo = sp.coo_matrix(m)
    coo.eliminate_zeros()
    tr, tc = coo.row // n, coo.col // n
    rows_t, cols_t = -(-m.shape[0] // n), -(-m.shape[1] // n)
    key = tr.astype(np.int64) * cols_t + tc
    tiles, inv = np.unique(key, return_inverse=True)
    vals = np.zeros((tiles.size, n, n), dtype=np.float32)
    vals[inv, coo.row % n, coo.col % n] = coo.data
    trow, tcol = tiles // cols_t, tiles % cols_t
    urows, starts = np.unique(trow, return_index=True)
    seg1 = np.append(starts, tiles.size)
    np.savetxt(f"{prefix}_mode_0_seg", [0, urows.size], fmt="%d")
    np.savetxt(f"{prefix}_mode_0_crd", urows, fmt="%d")
    np.savetxt(f"{prefix}_mode_1_seg", seg1, fmt="%d")
    np.savetxt(f"{prefix}_mode_1_crd", tcol, fmt="%d")
    np.savetxt(f"{prefix}_mode_vals", vals.reshape(-1), fmt="%.9g")
    Path(f"{prefix}_mode_shape").write_text(f"{rows_t}\n{cols_t}\n")
    return {"padded": [rows_t * n, cols_t * n], "stored_tiles": int(tiles.size)}


def write_blocked_1d(v, formats, prefix, n, orient, pad=0.0):
    """1-D vector (bias, BatchNorm vector) padded to a multiple of n; every stored coordinate holds a full n x n tile,
    because Comal's block reader takes n*n values per coordinate for every tensor (tensor.rs, chunks(N * N)).
    orient "col": tile[r][c] = v[k*n + c] (the vector broadcast over the rows of an output tile, indexed by its column);
    orient "row": tile[r][c] = v[k*n + r] (indexed by the row). The repeated values are simulated work."""
    L = -(-v.size // n) * n
    p = np.full(L, pad, dtype=np.float32)
    p[:v.size] = v
    segs = p.reshape(-1, n)
    tiles = np.repeat(segs[:, None, :], n, axis=1) if orient == "col" else np.repeat(segs[:, :, None], n, axis=2)
    if formats[0] == "dense":
        coords = np.arange(segs.shape[0])
    elif formats[0] == "compressed":
        coords = np.flatnonzero(segs.any(axis=1))
        np.savetxt(f"{prefix}_mode_0_seg", [0, coords.size], fmt="%d")
        np.savetxt(f"{prefix}_mode_0_crd", coords, fmt="%d")
    else:
        raise ValueError(f"1-D blocked writer handles dense or compressed, not {formats}")
    np.savetxt(f"{prefix}_mode_vals", tiles[coords].reshape(-1), fmt="%.9g")
    Path(f"{prefix}_mode_shape").write_text(f"{segs.shape[0]}\n")
    return {"padded": [L], "stored_tiles": int(coords.size), "orientation": orient}


# ---------------------------------------------------------------- vector layout (Comal patch 0027)
def write_vec_sparse(m, formats, prefix, b):
    """Sparse matrix whose values are scalars replicated over the b lanes (the graph's A in an aggregation): the scalar
    layout (every nonzero is one coordinate), each value written b times."""
    csr = sp.csr_matrix(m)
    csr.sum_duplicates()
    csr.eliminate_zeros()
    csr.sort_indices()
    rows, cols = csr.shape
    counts = np.diff(csr.indptr)
    if formats == ["compressed", "compressed"]:
        nz = np.flatnonzero(counts)
        np.savetxt(f"{prefix}_mode_0_seg", [0, nz.size], fmt="%d")
        np.savetxt(f"{prefix}_mode_0_crd", nz, fmt="%d")
        np.savetxt(f"{prefix}_mode_1_seg", np.concatenate([[0], np.cumsum(counts[nz])]), fmt="%d")
    elif formats == ["dense", "compressed"]:
        np.savetxt(f"{prefix}_mode_1_seg", csr.indptr, fmt="%d")
    else:
        raise ValueError(f"vector layout: sparse {formats} not handled")
    np.savetxt(f"{prefix}_mode_1_crd", csr.indices, fmt="%d")
    np.savetxt(f"{prefix}_mode_vals", np.repeat(csr.data.astype(np.float32), b), fmt="%.9g")
    Path(f"{prefix}_mode_shape").write_text(f"{rows}\n{cols}\n")
    return {"layout": "scalar coordinates, values replicated over the lanes", "nonzeros": int(csr.nnz)}


def write_vec_dense(a, formats, prefix, b, vectorize, pad=0.0):
    """1-D or 2-D dense array. vectorize: the last dimension in vectors of b lanes (padded with `pad`); else every value
    replicated over the lanes. A compressed level stores only the vectors holding a nonzero."""
    a = np.asarray(a, dtype=np.float32)
    if vectorize:
        L = -(-a.shape[-1] // b) * b
        p = np.full(a.shape[:-1] + (L,), pad, dtype=np.float32)
        p[..., :a.shape[-1]] = a
        blocks = p.reshape(a.shape[:-1] + (L // b, b))
    else:
        if a.size > 50_000_000:
            raise ValueError(f"vector layout: replicating a dense {a.shape} tensor over the lanes is too large "
                             "(vector mode targets the aggregation kernels)")
        blocks = np.repeat(a[..., None], b, axis=-1)
    present = np.any(blocks != 0, axis=-1)
    grid = present.shape
    if len(grid) == 1:
        idx = np.arange(grid[0]) if formats[0] == "dense" else np.flatnonzero(present)
        if formats[0] == "compressed":
            np.savetxt(f"{prefix}_mode_0_seg", [0, idx.size], fmt="%d")
            np.savetxt(f"{prefix}_mode_0_crd", idx, fmt="%d")
        vals = blocks[idx]
    else:
        rows = np.arange(grid[0]) if formats[0] == "dense" else np.flatnonzero(present.any(axis=1))
        if formats[0] == "compressed":
            np.savetxt(f"{prefix}_mode_0_seg", [0, rows.size], fmt="%d")
            np.savetxt(f"{prefix}_mode_0_crd", rows, fmt="%d")
        if formats[1] == "dense":
            vals = blocks[rows].reshape(-1, b)
        else:
            mask = present[rows]
            np.savetxt(f"{prefix}_mode_1_seg", np.concatenate([[0], np.cumsum(mask.sum(axis=1))]), fmt="%d")
            np.savetxt(f"{prefix}_mode_1_crd", np.nonzero(mask)[1], fmt="%d")
            vals = blocks[rows][mask]
    np.savetxt(f"{prefix}_mode_vals", np.asarray(vals).reshape(-1), fmt="%.9g")
    Path(f"{prefix}_mode_shape").write_text("".join(f"{g}\n" for g in grid))
    return {"layout": "vectors along the last dimension" if vectorize else "values replicated over the lanes",
            "grid": list(grid), "stored_vectors": int(np.asarray(vals).size // b)}


def unvec(fibers, vals, oshape, b):
    """Writer arrays of a vector-mode run -> dense output (rows x last dimension)."""
    from newmodels_kernel import output_dense
    raw = np.asarray(vals[0][1], dtype=np.float64)
    nv = raw.size // b
    if nv * b != raw.size:
        raise ValueError(f"{raw.size} values is not a multiple of {b}")
    grid = list(oshape[:-1]) + [-(-oshape[-1] // b)]
    ids, _, _ = output_dense(fibers, [(vals[0][0], list(range(1, nv + 1)))], grid)
    vecs = raw.reshape(nv, b)
    full = np.zeros(grid + [b])
    pos = np.nonzero(ids)
    full[pos] = vecs[ids[pos].astype(np.int64) - 1]
    full = full.reshape(list(oshape[:-1]) + [grid[-1] * b])
    return full[..., :oshape[-1]]


def unblock(fibers, vals, cshape, n):
    """Writer arrays of a true-block run -> dense array over the padded shape. The tile order is found by
    newmodels_kernel.output_dense on tile ids (the same level-order rule as every scalar output)."""
    from newmodels_kernel import output_dense
    raw = np.asarray(vals[0][1], dtype=np.float64)
    nt = raw.size // (n * n)
    if nt * n * n != raw.size:
        raise ValueError(f"{raw.size} values is not a multiple of {n * n}")
    if all(len(f[4]) == 1 for f in fibers) and nt == 1 and all(s == 1 for s in cshape):
        ids = np.ones(cshape)
    else:
        ids, _, _ = output_dense(fibers, [(vals[0][0], list(range(1, nt + 1)))], list(cshape))
    tiles = raw.reshape(nt, n, n)
    full = np.zeros((*cshape, n, n))
    pos = np.nonzero(ids)
    full[pos] = tiles[ids[pos].astype(np.int64) - 1]
    full = np.moveaxis(full, -2, -3)
    return full.reshape(*cshape[:-2], cshape[-2] * n, cshape[-1] * n)


# ---------------------------------------------------------------- single-operation reference
def single_op_reference(mlir_text, ins_by_arg):
    """float64 reference of a kernel with exactly one linalg operation, arguments bound by position."""
    sig = re.search(r"func\.func\s+@\w+\s*\((.*?)\)\s*->", mlir_text, re.S).group(1)
    argnames = re.findall(r"(%\w+)\s*:", sig)
    pos = {a: i for i, a in enumerate(argnames)}
    body = mlir_text[mlir_text.index(")", mlir_text.index("func.func")):]
    lin = re.findall(r"linalg\.(matmul|generic|add)\b", body)
    if len(lin) != 1:
        return None, f"{len(lin)} linalg operations"
    m = re.search(r"linalg\.\w+\s*(\{.*?\})?\s*ins\(([^:]*?):", body, re.S)
    ops = [o.strip() for o in m.group(2).split(",")]
    if not all(o in pos for o in ops):
        return None, f"inputs {ops} are not all function arguments"
    x = [ins_by_arg[pos[o]] for o in ops]
    dense = lambda a: a.toarray() if sp.issparse(a) else np.asarray(a)
    if lin[0] == "matmul":
        a, b = x
        return (a.astype(np.float64) @ dense(b).astype(np.float64) if sp.issparse(a)
                else dense(a).astype(np.float64) @ dense(b).astype(np.float64)), "matmul"
    if lin[0] == "add":
        return dense(x[0]).astype(np.float64) + dense(x[1]).astype(np.float64), "add"
    region = body[body.index("^bb0"):]
    region = region[:region.index("linalg.yield")]
    if "arith.addf" in region and len(x) == 2:
        a, b = dense(x[0]).astype(np.float64), dense(x[1]).astype(np.float64)
        return (a + (b[None, :] if b.ndim == 1 else b)), "add (bias broadcast over rows)" if b.ndim == 1 else "add"
    if "arith.cmpf" in region and "arith.select" in region and len(x) == 1:
        a = dense(x[0]).astype(np.float64)
        return np.where(a > 0, a, 0.0), "relu"
    return None, "operation not interpreted"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mlir", required=True)
    ap.add_argument("--dataset", nargs=2, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--blocks", type=int, nargs="+", default=[16, 32, 64])
    ap.add_argument("--paired", action="store_true")
    ap.add_argument("--ref-kernel", default=None, help="take the float64 reference of this kernel (e.g. the source of a "
                                                       "CSR copy, which computes the same function on the same values)")
    ap.add_argument("--mask-pad", choices=["auto", "off"], default="auto",
                    help="auto: in a kernel with a row max reduction (softmax), padded positions on the reduced axis hold "
                         "-1e30 (1-D inputs, e.g. the bias feeding the softmax; or, without a 1-D input, the padded columns "
                         "of the dense 2-D inputs), so padding does not enter the row max / row sum")
    ap.add_argument("--save", action="store_true", help="also save the inputs, the check target and every blocked output "
                                                         "(.npy/.npz in OUT) for diagnosis")
    ap.add_argument("--vector", type=int, default=None, choices=[16],
                    help="vector mode (Comal 0027): the output's last dimension in vectors of this many lanes, instead of "
                         "the block sizes; the graph's A keeps its scalar coordinates (values replicated over the lanes)")
    ap.add_argument("--perm", default=None, help="node permutation (.npy): run the blocked kernel on the reordered graph")
    ap.add_argument("--scalar-order-control", action="store_true", help="with --perm: also run the kernel in scalar mode "
                                                                        "on the natural and the reordered inputs")
    ap.add_argument("--scalar-only", action="store_true", help="only the scalar run (its cycles, its output checked "
                                                                "against the reference); no blocked run")
    args = ap.parse_args()
    if args.scalar_only:
        args.paired, args.blocks = True, []
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=False)
    mlir = MODELS / args.mlir
    kernel = mlir.stem
    result = {"kernel": kernel, "mlir": str(mlir), "dataset": args.dataset, "blocks": {}, "status": "running",
              "timing": "Comal native true-block timing (decision D1 = a)", "hbm": False}
    write = lambda: (out / "result.json").write_text(json.dumps(result, indent=1) + "\n")
    write()
    os.environ.setdefault("DATA_PATH", "/tmp/data")
    os.environ["COMAL_ENABLE_HBM"] = "0"
    os.environ["TORCH_WEIGHTS_ONLY_LOAD"] = "0"
    os.chdir(ARTIFACT)
    sys.path.insert(0, str(ARTIFACT / "scripts"))
    t0 = time.time()
    try:
        import comal
        import b2_block_timing as b2
        captured = {}

        def intercept(op, data):
            captured.update(op=op, data=data)
            return True, 0                                     # not simulated here: S is the trusted scalar result

        comal.run_graph = intercept
        import run_end_to_end as r
        from utils import get_tensors_properties
        from newmodels_kernel import NoReference, output_dense, read_tensor, reference
        argv = ["--infile", str(mlir), "--build", BUILD, "-sp", "0.9", "-par", "1", "--useGen",
                "-inDataset", args.dataset[0], "-inData", args.dataset[1]]
        r.run_fuseflow_all(r.get_argparser().parse_args(argv))
        if not captured:
            raise RuntimeError("run_end_to_end did not reach the simulation")
        op = out / "op.bin"
        shutil.copy(captured["op"], op)
        data = Path(captured["data"])
        sam = mlir.parent / f"{kernel}_sam.mlir"
        shutil.copy(sam, out / "sam.mlir")
        header = get_tensors_properties(sam)
        shapes = {k: [int(v) for v in (data / f"tensor_{k}_mode_shape").read_text().split()]
                  for k in header if (data / f"tensor_{k}_mode_vals").exists()}
        ins = {k: read_tensor(str(data / f"tensor_{k}"), header[k], shapes[k]) for k in shapes}
        by_arg = {header[k]["Arg"]: v for k, v in ins.items() if isinstance(header[k]["Arg"], int)}
        w = [v for k, v in ins.items() if not isinstance(header[k]["Arg"], int) and v.ndim == 2]
        b = [v for k, v in ins.items() if not isinstance(header[k]["Arg"], int) and v.ndim == 1]
        result["inputs"] = {k: {"shape": shapes[k], "format": header[k]["format"], "arg": header[k]["Arg"]} for k in shapes}
        ref, how = None, None
        try:
            ref = np.asarray(reference(args.ref_kernel or kernel, by_arg, w, b, np.float64), dtype=np.float64)
            how = f"newmodels_kernel.reference (float64){' of ' + args.ref_kernel if args.ref_kernel else ''}"
        except Exception as e:
            if not (isinstance(e, NoReference) or str(e).startswith("no reference")):
                raise                                          # a reference exists but failed: a real error
            if w or b:
                how = "no reference; the kernel reads constants (weights/biases not passed as arguments)"
            else:
                ref, how = single_op_reference(mlir.read_text(), by_arg)
                how = f"single-operation reference ({how})" if ref is not None else f"no reference ({how})"
        scalar_cache = {}

        def run_scalar():
            """FuseFlow's own scalar run of the same compiled kernel on the same files (once per kernel)."""
            if "out" not in scalar_cache:
                passed, cyc, fibers, vals = b2.comal_call(comal.run_graph_outputs, op, data, out / "scalar.log")
                shape = list(ref.shape) if ref is not None else None
                if shape is None:
                    n_ = max(s[0] for s in shapes.values())
                    inner = [f for f in fibers if len(f[3]) != 2] or fibers
                    shape = [n_, max(int(np.max(f[4])) + 1 for f in inner if len(f[4]))]
                scalar_cache["out"] = output_dense(fibers, vals, shape)[0]
                result["paired_scalar"] = {"passed": passed, "cycles": cyc}
                if ref is not None:
                    result["paired_scalar"]["vs_ref"] = compare(scalar_cache["out"], ref)
            return scalar_cache["out"]

        scalar = run_scalar() if args.paired else None
        if ref is None and scalar is None:
            result.update(status="unchecked", reason=f"no reference ({how}) and no paired scalar run")
            write()
            return 1
        result["check"] = how if ref is not None else "paired scalar run"
        target = ref if ref is not None else scalar
        oshape = list(target.shape)
        Pf = lambda a: a
        if args.perm:
            # node reordering (H_R ablation): A becomes P A P^T and every node-indexed axis of every input is permuted;
            # the check target is permuted the same way (the blocked output is compared in the reordered numbering)
            perm = np.load(args.perm)
            nn = int(perm.size)

            def Pf(a):
                if a is None:
                    return None
                if sp.issparse(a):
                    a = sp.csr_matrix(a)
                    if a.shape[0] == nn:
                        a = a[perm]
                    if a.shape[1] == nn:
                        a = a[:, perm]
                    return sp.csr_matrix(a)
                a = np.asarray(a)
                for ax in range(a.ndim):
                    if a.shape[ax] == nn:
                        a = np.take(a, perm, axis=ax)
                return a
            permuted = sorted(k for k, a in ins.items() if nn in a.shape)
            if not permuted:
                raise ValueError(f"--perm: no input has the node dimension {nn}: {[(k, a.shape) for k, a in ins.items()]}")
            ins0, target0 = ins, target
            ins = {k: Pf(a) for k, a in ins.items()}
            target = Pf(target)
            result["reorder"] = {"perm": args.perm, "nodes": nn, "permuted_inputs": permuted}
            if args.scalar_order_control:
                # control: the same kernel in SCALAR mode on the natural and on the reordered inputs, both written by the
                # blocked writers at n = 1 (one value per tile = the scalar layout)
                ctl = {}
                for label, src, tgt in (("natural", ins0, target0), ("reordered", ins, target)):
                    sd = out / f"scalar_{label}_data"
                    sd.mkdir()
                    for k, a in src.items():
                        fmt = header[k]["format"]
                        if a.ndim == 1:
                            write_blocked_1d(np.asarray(a, dtype=np.float32), fmt, str(sd / f"tensor_{k}"), 1, "col")
                        elif sp.issparse(a):
                            write_blocked_sparse(a, fmt, str(sd / f"tensor_{k}"), 1)
                        else:
                            write_blocked_dense(np.asarray(a, dtype=np.float32), fmt, str(sd / f"tensor_{k}"), 1)
                    passed, cyc, fibers, vals = b2.comal_call(comal.run_graph_outputs, op, sd, out / f"scalar_{label}.log")
                    got = output_dense(fibers, vals, oshape)[0]
                    ctl[label] = {"passed": passed, "cycles": cyc, "check": compare(got, tgt)}
                    shutil.rmtree(sd, ignore_errors=True)
                    print(f"scalar {label}", json.dumps(ctl[label]), flush=True)
                result["scalar_order_control"] = ctl
                write()
        if args.save:
            np.save(out / "target.npy", target)
            for k, a in ins.items():
                if sp.issparse(a):
                    sp.save_npz(out / f"in_{k}.npz", sp.csr_matrix(a))
                else:
                    np.save(out / f"in_{k}.npy", np.asarray(a))
        has_1d = any(a.ndim == 1 for a in ins.values())
        mask = args.mask_pad == "auto" and has_row_max(mlir.read_text())
        result["mask_pad"] = {"row_max_reduction": has_row_max(mlir.read_text()), "applied": mask,
                              "where": ("1-D inputs" if has_1d else "padded columns of dense 2-D inputs") if mask else None}
        if args.vector:
            # vector mode: one run, recorded as blocks["v16"] (same record and checks as a block size)
            vb = args.vector
            W = oshape[-1]
            rec = {}
            vd = out / f"v{vb}_data"
            vd.mkdir()
            try:
                for k, a in ins.items():
                    fmt = header[k]["format"]
                    vec = a.shape[-1] == W
                    pad = MASK if (mask and ((a.ndim == 1 and has_1d) or (a.ndim == 2 and not has_1d))) else 0.0
                    if sp.issparse(a) and not vec:
                        rec[k] = write_vec_sparse(a, fmt, str(vd / f"tensor_{k}"), vb)
                    else:
                        rec[k] = write_vec_dense(a.toarray() if sp.issparse(a) else a, fmt, str(vd / f"tensor_{k}"), vb, vec, pad)
                fn = getattr(comal, f"run_graph_vector{vb}_outputs")
                passed, cyc, fibers, vals = b2.comal_call(fn, op, vd, out / f"v{vb}.log")
                got = unvec(fibers, vals, oshape, vb)
                if args.save:
                    np.save(out / f"v{vb}.npy", got)
                chk = compare(got, target)
                rec = {"passed": passed, "cycles": cyc, "inputs": rec, "check": chk,
                       "status": "ok" if passed and chk["failing"] == 0 else ("sim-failed" if not passed else "mismatch")}
                if rec["status"] == "mismatch" and ref is not None:
                    rec["check"]["baseline"] = baseline_accept(got, Pf(ref), Pf(run_scalar()))
                    if rec["check"]["baseline"]["accepted"]:
                        rec["status"] = "ok"
            except BaseException as e:
                if isinstance(e, (KeyboardInterrupt, SystemExit)):
                    raise
                st = "sim-failed" if type(e).__name__ == "PanicException" else "error"
                rec = {"status": st, "reason": f"{type(e).__name__}: {e}"[:400], "inputs": rec}
            shutil.rmtree(vd, ignore_errors=True)
            result["blocks"][f"v{vb}"] = rec
            write()
            print(f"v{vb}", json.dumps({k: v for k, v in rec.items() if k != "inputs"}), flush=True)
            args.blocks = []
        for n in args.blocks:
            tries = []
            for orient in (("col", "row") if has_1d else ("col",)):
                rec = {}
                bd = out / f"block{n}_data"
                bd.mkdir()
                try:
                    for k, a in ins.items():
                        fmt = header[k]["format"]
                        if a.ndim == 1:
                            rec[k] = write_blocked_1d(np.asarray(a, dtype=np.float32), fmt, str(bd / f"tensor_{k}"), n, orient,
                                                             MASK if mask else 0.0)
                        elif sp.issparse(a):
                            rec[k] = write_blocked_sparse(a, fmt, str(bd / f"tensor_{k}"), n)
                        else:
                            rec[k] = write_blocked_dense(np.asarray(a, dtype=np.float32), fmt, str(bd / f"tensor_{k}"), n,
                                                                mask and not has_1d)
                    fn = getattr(comal, f"run_graph_true_block{n}_outputs")
                    passed, cyc, fibers, vals = b2.comal_call(fn, op, bd, out / f"block{n}_{orient}.log")
                    cshape = [-(-s // n) for s in oshape]
                    got = unblock(fibers, vals, cshape, n)[tuple(slice(0, s) for s in oshape)]
                    if args.save:
                        np.save(out / f"block{n}_{orient}.npy", got)
                    chk = compare(got, target)
                    rec = {"passed": passed, "cycles": cyc, "inputs": rec, "check": chk,
                           "status": "ok" if passed and chk["failing"] == 0 else ("sim-failed" if not passed else "mismatch")}
                    if rec["status"] == "mismatch" and ref is not None:
                        rec["check"]["baseline"] = baseline_accept(got, Pf(ref), Pf(run_scalar()))
                        if rec["check"]["baseline"]["accepted"]:
                            rec["status"] = "ok"
                except BaseException as e:                     # a Comal panic is a BaseException (pyo3 PanicException)
                    if isinstance(e, (KeyboardInterrupt, SystemExit)):
                        raise
                    st = "sim-failed" if type(e).__name__ == "PanicException" else "error"
                    rec = {"status": st, "reason": f"{type(e).__name__}: {e}"[:400], "inputs": rec}
                shutil.rmtree(bd, ignore_errors=True)
                if has_1d:
                    rec["orientation_1d"] = orient
                tries.append(rec)
                if rec["status"] != "mismatch":                  # the other orientation only after a wrong output
                    break
            if len(tries) > 1:
                # both orientations wrong: report the closer one (fewest failing elements), and every try
                if rec["status"] == "mismatch":
                    rec = min(tries, key=lambda t: (t.get("check") or {}).get("failing", float("inf")))
                rec = dict(rec, tries=[{k: v for k, v in t.items() if k != "inputs"} for t in tries])
            result["blocks"][str(n)] = rec
            write()
            print(f"block{n}", json.dumps({k: v for k, v in rec.items() if k != "inputs"}), flush=True)
        result["status"] = "done"
        shutil.rmtree(data, ignore_errors=True)
    except BaseException as e:                                 # incl. a Comal panic outside the block loop
        if isinstance(e, (KeyboardInterrupt, SystemExit)):
            raise
        result.update(status="error", reason=f"{type(e).__name__}: {e}"[:600], trace=traceback.format_exc()[-2000:])
    result["wall_seconds"] = round(time.time() - t0, 1)
    import resource
    result["peak_rss_gb"] = round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1e6, 2)   # Linux: KB
    write()
    print(json.dumps({k: result.get(k) for k in ("kernel", "dataset", "status", "check", "reason")}), flush=True)
    return 0 if result["status"] == "done" else 1


